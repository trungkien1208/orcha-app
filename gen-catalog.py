#!/usr/bin/env python3
"""Writes mods/orcha/catalog.js (the working rules and suggested skills)
from orcha's src/orcha_rules.rs, so the app and the terminal orcha offer the
same list from one source. Run it when orcha's RULES or SKILLS change:

    python3 gen-catalog.py                  # orcha's file on GitHub
    python3 gen-catalog.py ../orcha         # a local orcha checkout
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TARGET = ROOT / "mods" / "orcha" / "catalog.js"
REMOTE = "https://raw.githubusercontent.com/trungkien1208/orcha/orcha/src/orcha_rules.rs"


def source_text():
    if len(sys.argv) > 1:
        return (Path(sys.argv[1]) / "src" / "orcha_rules.rs").read_text()
    with urllib.request.urlopen(REMOTE, timeout=20) as response:
        return response.read().decode()


def rust_string(literal):
    """The value of a Rust "..." literal: escapes, and backslash-newline
    continuations that drop the next line's leading whitespace."""
    out, i = [], 0
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        nxt = literal[i + 1]
        if nxt == "\n":
            i += 2
            while i < len(literal) and literal[i] in " \t\n":
                i += 1
            continue
        out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}[nxt])
        i += 2
    return "".join(out)


def blocks(text, const):
    body = text[text.index(f"pub(crate) const {const}"):]
    body = body[: body.index("\n];") + 3]
    return re.findall(r"\{\n(.*?)\n    \},", body, re.S)


def fields(block):
    found = {}
    for name, literal in re.findall(r'(\w+): "((?:[^"\\]|\\.)*)"', block, re.S):
        found[name] = rust_string(literal)
    lists = re.findall(r"(\w+): &\[(.*?)\]", block, re.S)
    for name, items in lists:
        found[name] = [rust_string(s) for s in re.findall(r'"((?:[^"\\]|\\.)*)"', items)]
    return found


def main():
    text = source_text()
    rules = [fields(b) for b in blocks(text, "RULES")]
    skills = [fields(b) for b in blocks(text, "SKILLS")]
    for rule in rules:
        assert {"id", "title", "summary", "body"} <= rule.keys(), rule
    for skill in skills:
        assert {"name", "title", "summary", "group", "source", "skills"} <= skill.keys(), skill
    TARGET.write_text(
        "// Generated by gen-catalog.py from orcha's src/orcha_rules.rs: do not edit.\n"
        f"export const RULES = {json.dumps(rules, indent=2, ensure_ascii=False)};\n\n"
        f"export const SKILLS = {json.dumps(skills, indent=2, ensure_ascii=False)};\n"
    )
    print(f"{TARGET.relative_to(ROOT)}: {len(rules)} rules, {len(skills)} skills")


if __name__ == "__main__":
    main()
